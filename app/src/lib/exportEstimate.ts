import { TIMELINE_DURATION } from './animTimeline';

/** تقدير حجم مخرَج الفيديو، للتذييل الحيّ في حوار التصدير
 * (`re-capcut-flows.md` §4.2: «المدّة: 3s | الحجم: حوالي 4 MB»، ويتحدّث مع كل تغيير).
 *
 * **لماذا تقديرٌ وليس رقمًا دقيقًا، وعلى أي أساس.** MP4 يُرمَّز بـ`libx264` بمعدّل
 * جودة ثابت (CRF 18 للعالية و23 للمتوسطة)، لا بمعدّل بِت ثابت — فالحجم تابعٌ للمحتوى
 * ولا يُعرَف قبل الترميز. فالمعروض **بت لكل بكسل (bpp)**، ويُكتب دائمًا بعلامة «≈».
 *
 * القيم أدناه **مقيسة لا مُقدَّرة**، على ثلاثة مخرجات حقيقية من تطبيق Tauri المبنيّ
 * (نسخة ffmpeg المرفقة 9.0.2)، لإعلانٍ عموديٍّ من هذا النوع بالضبط — نصّ عربي
 * ومساحات لون صلبة على خلفية واحدة، وهو المحتوى الذي يصنعه مزيج فعلًا — عند
 * 1080×1920 و30fps ومدّة 5 ثوانٍ، ١٨ أكتوبر ٢٠٢٦:
 *
 * | الصيغة | الجودة | الحجم الفعلي | bpp = بِت ÷ (عرض×ارتفاع×fps×مدّة) |
 * |---|---|---|---|
 * | MP4 (CRF 18) | عالية | 91,314 بايت | 0.00235 |
 * | MP4 (CRF 23) | متوسطة | 69,104 بايت | 0.00178 |
 * | GIF @15fps | — | 271,060 بايت | 0.01394 |
 *
 * محتوًى كهذا ضعيف التفاصيل جدًّا، فـbpp فيه أصغر بمراتب من مشاهد الكاميرا — ولهذا
 * لا تصلح أرقام الفيديو العامّة هنا. من يُعيد التعيير لاحقًا: صدِّر فعليًا، ثم
 * `ffprobe -show_entries format=size` واقسم على الحاصل نفسه.
 *
 * GIF منفصلٌ تمامًا: لوحة ألوان مفهرسة بعد `palettegen`، فحجمه يتبع عدد البكسلات
 * المتغيّرة بين الإطارات لا تعقيد الصورة — ومعدّله هنا نحو ستّة أضعاف H.264.
 * وجودتا GIF متساويتان لأن مسار الترميز لا يقرأ `quality` أصلًا (مرحلتا
 * palettegen/paletteuse فقط)، فلا يصحّ أن يتغيّر التقدير بتغييرٍ لا أثر له.
 */
const BITS_PER_PIXEL: Record<'mp4' | 'gif', Record<'high' | 'med', number>> = {
  mp4: { high: 0.00235, med: 0.00178 },
  gif: { high: 0.01394, med: 0.01394 },
};

/** مُضاعِف الدقّة الفعلي عند التصدير.
 *
 * مُضاعِف ١×/٢×/٣× مفهومٌ خاصٌّ بالصور الثابتة (شاشة Retina). على الفيديو كان يُطبَّق
 * كما هو، والافتراضي ٢ — فمشروع «تيك توك» المكتوب على بطاقته **1080 × 1920** كان
 * يُنتج ملف MP4 بأبعاد **2160 × 3840**: أربعة أمثال البكسلات، وترميزٌ أبطأ بالقدر
 * نفسه، ونصٌّ على البطاقة يخالف الملف. ولا منصّة من منصّات هذا الفهرس تَقبل أكثر من
 * الدقّة المذكورة أصلًا. فالفيديو يُصدَّر بدقّة اللوحة نفسها (١×)، ومُبدِّل المقياس
 * يُعطَّل بسببٍ مكتوب — نفس نمط تعطيل «خلفية شفافة» على MP4. */
export function effectiveExportScale(format: string, scale: number): number {
  return format === 'mp4' || format === 'gif' ? 1 : scale;
}

export interface VideoEstimate {
  /** مدّة المخرَج بالثواني — مدّة الخط الزمني نفسها، لا تقدير. */
  seconds: number;
  /** عدد الملفات التي ستُكتب فعلًا (هدفٌ لكل مقاس مختار × عدد اللوحات). */
  files: number;
  /** مجموع الحجم التقديري بالميغابايت، مقرَّبًا لمنزلة واحدة. */
  megabytes: number;
}

/** `dims` أبعاد كل ملفٍ سيُكتب (بعد `exportScale`)؛ الحجم مجموعٌ عليها كلها لأن
 * التذييل يُقدّر ما يُنتجه الزرّ عند ضغطه، لا ملفًا واحدًا منها. */
export function estimateVideoExport(dims: { w: number; h: number }[], format: 'mp4' | 'gif', fps: number, quality: 'high' | 'med'): VideoEstimate {
  const bpp = BITS_PER_PIXEL[format][quality];
  const bits = dims.reduce((sum, d) => sum + d.w * d.h * fps * TIMELINE_DURATION * bpp, 0);
  return {
    seconds: TIMELINE_DURATION,
    files: dims.length,
    // منزلتان لا واحدة: مخرجات هذا النوع من المحتوى تقع تحت ١ م.ب فعلًا (0.09 م.ب
    // للملف المقيس أعلاه)، فالتقريب لمنزلة واحدة كان يطبعها كلّها «0.1 م.ب».
    megabytes: Math.max(0.01, Math.round((bits / 8 / 1_000_000) * 100) / 100),
  };
}
