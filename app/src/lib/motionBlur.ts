// ضبابُ الحركة — الغالقُ الذي يفتح على فترةٍ لا على لحظة.
//
// ═══════════════════════════════════════════════════════════════════════════
// (١) لماذا لا يُصنَع بالتخفيف
// ═══════════════════════════════════════════════════════════════════════════
// التخفيفُ (`easing`) يَحكم **أين** يكون العنصرُ عند اللحظة t. وضبابُ الحركة لا
// يسأل عن ذلك: هو أثرُ أن الغالقَ بقي مفتوحًا بين t و t+φΔ، فسجّل **كلَّ** المواضع
// التي مرّ بها العنصرُ في تلك الفترة على البكسل نفسه.
//
// والفرقُ قابلٌ للقياس في إطارٍ واحد: عنصرٌ مُضبَّبٌ وجارٌ له حادٌّ **في الإطار
// نفسِه**. ولا دالّةَ تخفيفٍ تُنتج ذلك، لأن التخفيفَ يُعطي لكلّ عنصرٍ موضعًا واحدًا
// في الإطار الواحد مهما كان شكلُ منحناه. فالمسألةُ عددُ العيّنات لا شكلُ المنحنى.
//
// ═══════════════════════════════════════════════════════════════════════════
// (٢) جدولُ العيّنات — ولماذا `k/N` لا `(k+½)/N`
// ═══════════════════════════════════════════════════════════════════════════
// الغالقُ يفتح **عند** زمن الإطار ويبقى مفتوحًا `φ = angle/360` من فترة الإطار:
//
//     t_k = t + (k / N) · φ · Δ        حيث k = 0 … N−1  و  Δ = 1/fps
//
// والصيغةُ `k/N` اختيارٌ له برهان، لا ذوق. فالبديلُ `(k+½)/N` يُعطي عند `N = 1`
// عيّنةً واحدةً عند `t + ½φΔ` — أي أن **إطفاءَ الضباب يُزيح كلَّ إطارٍ في كلّ
// مستندٍ قائم**. أمّا `k/N` فتُعطي عند `N = 1` المصفوفةَ `[t]` بعينها، فيكون
// «بلا ضباب» هو الكودَ القائمَ حرفًا بحرف لا تقريبًا منه. وهذه متطابقةٌ تُقاس:
// `qa/motion-blur.spec.mjs` §١.
//
// وتبقى الأزمنةُ **مشتقّةً من الفهرس بلا تراكم** — وهي الخصلةُ التي تَحرسها
// `videoExport.ts:73-78` ورصدتها الورقتان: `t_k` دالّةٌ في `i` و`k` وحدهما، فلا
// مُجمِّعَ عائمٌ يَنجرف عبر ثلاثمئة إطار.
//
// ═══════════════════════════════════════════════════════════════════════════
// (٣) ولا ساعةَ ثانية — وهذا هو موضعُ التصادم مع قياسٌ خارجيٌّ موثَّق`
// ═══════════════════════════════════════════════════════════════════════════
// تقول الخطّةُ هناك: «لا مصدرَ زمنٍ ثانٍ. التصديرُ يَشتقّ `i / fps` **وعليه أن
// يبقى كذلك**». وقارئٌ عَجِلٌ يرى هنا `N` زمنًا لكلّ إطارٍ فيَحسبها نقضًا.
//
// وليست كذلك، والفرقُ مُسمًّى: الخطّةُ تَمنع **ساعةً** ثانية — أي مصدرَ زمنٍ
// مستقلًّا يَجري بنفسه، وشاهدُها `StudioContext.tsx:821-835` الذي يُكامِل فارقَ
// ساعةِ الحائط. وذاك يُنتج أزمنةً تختلف بين جهازٍ وجهاز وبين تشغيلٍ وتشغيل.
// أمّا `t_k` فليست ساعةً: هي **اشتقاقٌ نقيٌّ** من `i / fps` ومن `k` و`N` و`φ`،
// وكلُّها أعدادٌ في المستند. فالمُخرَجُ يبقى قابلًا لإعادة الإنتاج بتّةً ببتّة على
// أيّ جهازٍ تحت أيّ حِمل — وهو بالضبط ما كانت القاعدةُ تَحرسه.
//
// وتبقى من الخطّة قاعدةٌ ثالثةٌ تُطاع هنا حرفيًّا (`:1061-1065`): **لا حيلةَ أداءٍ
// تختار بين مسارَين متشابهَين بصريًّا**. ولهذا **لا يوجد** في هذا الملفّ ولا فيما
// يُناديه شرطُ «إن لم يتحرّك شيءٌ فتخطَّ التجميع» — وهو تحسينٌ مغرٍ ومُخرَجُه
// مطابقٌ بالبِت. والسببُ أن قيمةَ `N` يجب أن تبقى **إعلانًا من المصمّم** يُقرأ من
// المستند، لا استنتاجًا من محتواه: متى صارت تُشتقّ من المحتوى صار زمنُ التصدير
// دالّةً في المستند بطريقةٍ لا تَظهر في أيّ سطحٍ يراه المصمّم.
//
// ═══════════════════════════════════════════════════════════════════════════
// (٤) التجميعُ متوسّطٌ جارٍ — ولماذا ليس `globalAlpha = 1/N`
// ═══════════════════════════════════════════════════════════════════════════
// الخاطئُ البديهيّ: ارسم كلَّ عيّنةٍ بـ`globalAlpha = 1/N` فوق لوحةٍ ممسوحة. و
// `source-over` تَحسب `a·src + (1−a)·dst` لا `a·src + dst`، فيخرج آخرُ عيّنةٍ
// بوزن `1/N` والأولى بوزن `(1−1/N)^(N−1)/N` — أي أن العيّنات **غيرُ متساوية
// الوزن** ويَغلب عليها الذيل.
//
// والصحيحُ متوسّطٌ جارٍ: العيّنةُ `k` تُرسَم بـ`globalAlpha = 1/(k+1)`، فتُعطي
// `dst = (1/(k+1))·s_k + (k/(k+1))·dst_prev` — وهو تعريفُ المتوسّط الجاري
// بالاستقراء. فالأوزانُ متساويةٌ `1/N` لكلّ عيّنةٍ بالضبط.
export interface ShutterSpec {
  /** عددُ العيّنات لكلّ إطارٍ مُخرَج. `1` يعني «بلا ضباب» وهو المسارُ القائم. */
  samplesPerFrame: number;
  /** زاويةُ الغالق بالدرجات. ١٨٠ هي عُرفُ السينما: الغالقُ مفتوحٌ نصفَ فترة
   * الإطار. و٣٦٠ يعني مفتوحًا طوالَ الفترة — أقصى ضبابٍ ممكن بلا تداخلٍ بين
   * إطارين. */
  angle: number;
}

/** الغالقُ المُطفأ: عيّنةٌ واحدةٌ عند زمن الإطار بعينه. */
export const SHUTTER_OFF: ShutterSpec = { samplesPerFrame: 1, angle: 180 };

/** عددُ العيّنات المعروضُ في لوحة التصدير.
 *
 * **والثمنُ دون الخطّيّ، وهذا قيس ولم يُفترَض.** كان المكتوبُ هنا أوّلًا «الثمنُ
 * خطّيٌّ فتَضعيفُ القيمة يُضاعف الزمن»، فقيس على شكل المرجع بعينه — ٢٥٦٠×١٤٤٠ ·
 * ١٢ث · ٣٠ إطارًا/ث · ٣٦٠ إطارًا — فخرج غيرَ ذلك:
 *
 *     N=1  2.45ث   ×1.00        N=8   10.72ث  ×4.38
 *     N=2  4.16ث   ×1.70        N=16  20.22ث  ×8.25
 *     N=4  6.02ث   ×2.46
 *
 * فالمُعامِلُ نحو **نصفِ N** لا N. والسببُ أن لكلّ إطارٍ ثمنًا لا يتعلّق بعدد
 * العيّنات — `toBlob` وترميزُ PNG — يُدفَع مرّةً واحدةً مهما كُرّرت الرسمة.
 * والأرقامُ تُعاد بـ`qa/motion-blur.spec.mjs` §٥. */
export const SHUTTER_SAMPLE_OPTIONS = [1, 2, 4, 8, 16] as const;

/** زاويةُ الغالق المُثبَّتة. تُعرَض قيمةً واحدةً ولا تُجعَل مِقبضًا ثانيًا: المِقبضُ
 * الذي يَفهمه المصمّمُ هو «كم ضبابًا» لا «كم درجةً»، وزاويتان مع عددَي عيّناتٍ
 * تُنتجان نفسَ المظهر بطريقتين فتصير اللوحةُ أسئلةً بلا أجوبةٍ مميّزة. */
export const DEFAULT_SHUTTER_ANGLE = 180;

export function normalizeShutter(s: ShutterSpec | undefined | null): ShutterSpec {
  if (!s) return SHUTTER_OFF;
  const samplesPerFrame = Math.max(1, Math.round(s.samplesPerFrame));
  const angle = Math.min(360, Math.max(0, s.angle));
  return { samplesPerFrame, angle };
}

/** هل لهذا الغالق أثرٌ أصلًا؟ عيّنةٌ واحدةٌ أو زاويةُ صفرٍ تُعطيان `[t]` فقط. */
export function shutterIsOpen(s: ShutterSpec): boolean {
  return s.samplesPerFrame > 1 && s.angle > 0;
}

/** أزمنةُ العيّنات لإطارٍ واحد.
 *
 * `frameInterval` هي `1/fps` وتُمرَّر صراحةً: هذه الوحدةُ لا تعرف معدّلَ الإطارات
 * ولا الحالة، كما لا تعرفهما `renderArtboardFrames` — والفصلُ هو ما يُبقي الأزمنةَ
 * مشتقّةً من وسائطَ مكتوبةٍ لا من حالةٍ تَجري. */
export function shutterSampleTimes(frameTime: number, frameInterval: number, shutter: ShutterSpec): number[] {
  const s = normalizeShutter(shutter);
  if (!shutterIsOpen(s)) return [frameTime];
  const span = (s.angle / 360) * frameInterval;
  const out: number[] = new Array(s.samplesPerFrame);
  for (let k = 0; k < s.samplesPerFrame; k++) out[k] = frameTime + (k / s.samplesPerFrame) * span;
  return out;
}

/** وزنُ العيّنة `k` في المتوسّط الجاري — انظر (٤) أعلاه. يُصدَّر لأن الاختبار
 * يُبرهن عليه عددًا، لا على أثره في البكسل وحده. */
export const runningMeanAlpha = (k: number): number => 1 / (k + 1);
