const lerp = (a, b, f) => a + (b - a) * f;
const clamp01 = (f) => Math.min(1, Math.max(0, f));

/** مستطيلٌ مصمت داخل مخزن RGB24. الإحداثيّات بالبكسل المطلق لأن الحقيقة الأرضيّة
 * بالبكسل: «١٤٠ بكسلًا من اليسار» لا «١٣٪». البنود وحدها نسبيّة. */
function fillRect(buf, W, H, x, y, w, h, [r, g, b]) {
  const x0 = Math.max(0, Math.round(x));
  const y0 = Math.max(0, Math.round(y));
  const x1 = Math.min(W, Math.round(x + w));
  const y1 = Math.min(H, Math.round(y + h));
  for (let yy = y0; yy < y1; yy++) {
    let i = (yy * W + x0) * 3;
    for (let xx = x0; xx < x1; xx++) {
      buf[i++] = r;
      buf[i++] = g;
      buf[i++] = b;
    }
  }
}

/** مستطيلٌ بحوافَّ رأسيّةٍ مُنعَّمة — لأن الموضعَ الكسريَّ يجب أن يَظهر في البكسل.
 *
 * `fillRect` يُقرِّب y إلى عددٍ صحيح، فعنصرٌ ينزل ٠٫٤ بكسل للإطار يبقى في مكانه
 * أربعةَ إطاراتٍ ثم يَقفز واحدًا. وذلك يُفسِد شاهدَي **التجاوز** (٤ بكسلات) و
 * **الانجراف** (٠٫٤ بكسل للإطار) معًا: الحقيقةُ الأرضيّةُ كسريّةٌ والصورةُ
 * صحيحة، فلا نعرف هل أخطأ المقياسُ أم أخطأ الشاهد. فالصفُّ الجزئيُّ أعلى الشكل
 * وأسفلَه يُمزَج بالخلفيّة بنسبة تغطيته — وهو ما يفعله أيُّ رسّامٍ حقيقيّ. */
function fillRectAAY(buf, W, H, x, y, w, h, [r, g, b], bg) {
  const x0 = Math.max(0, Math.round(x));
  const x1 = Math.min(W, Math.round(x + w));
  const yTop = y;
  const yBot = y + h;
  const yi0 = Math.max(0, Math.floor(yTop));
  const yi1 = Math.min(H, Math.ceil(yBot));
  for (let yy = yi0; yy < yi1; yy++) {
    // تغطيةُ هذا الصفّ: الجزءُ المشترك بين [yy, yy+1] و[yTop, yBot].
    const cover = Math.max(0, Math.min(yy + 1, yBot) - Math.max(yy, yTop));
    if (cover <= 0) continue;
    const cr = Math.round(bg[0] + (r - bg[0]) * cover);
    const cg = Math.round(bg[1] + (g - bg[1]) * cover);
    const cb = Math.round(bg[2] + (b - bg[2]) * cover);
    let i = (yy * W + x0) * 3;
    for (let xx = x0; xx < x1; xx++) {
      buf[i++] = cr;
      buf[i++] = cg;
      buf[i++] = cb;
    }
  }
}

function fillBackground(buf, bg) {
  for (let i = 0; i < buf.length; i += 3) {
    buf[i] = bg[0];
    buf[i + 1] = bg[1];
    buf[i + 2] = bg[2];
  }
}

/** إطارُ الهدف عند الزمن t. هذه هي الدالّة التي تمثّل الحقيقة الأرضيّة كلّها.
 *
 * و`barEase` وسيطٌ لا زينة: شاهدُ «الاقتحام» هو هذا الإطارُ نفسُه بدرجةِ تدرّجٍ
 * واحدة — دالّةُ عتبةٍ بدل الخطّ المستقيم. فلا يختلف الشاهدان في بكسلٍ آخر، ولا
 * يَفصلهما إلا البندُ المقصود. */
function renderTargetFrame(t, W = COMP.width, H = COMP.height, barEase = (f) => f) {
  const buf = Buffer.alloc(W * H * 3);
  fillBackground(buf, COMP.bg);
  const { plate, bar, dot } = COMP;
  fillRect(buf, W, H, plate.x, plate.y, plate.w, plate.h, plate.color);

  // الشريط: عرضٌ صفرٌ قبل t0 يعني «غير موجود»، لا «موجودٌ بعرض بكسل».
  const barF = barEase(clamp01((t - bar.t0) / (bar.t1 - bar.t0)));
  if (barF > 0) fillRect(buf, W, H, bar.x, bar.y, bar.wFull * barF, bar.h, bar.color);

  const dotF = clamp01((t - dot.t0) / (dot.t1 - dot.t0));
  fillRect(buf, W, H, lerp(dot.x0, dot.x1, dotF), dot.y, dot.w, dot.h, dot.color);
  return buf;
}

