// وإلّا دارت الصيغةُ على نفسها: مسارٌ أطولُ أسرعُ فمسحتُه أوسعُ فـδ أكبرُ فالمسارُ
// أطول. ومسحةُ هذا الشاهد أوسعُ قليلًا (٨٢٥ ÷ ٧٫٥ إطارًا = ١١٠ بكسل/إطار) وذلك
