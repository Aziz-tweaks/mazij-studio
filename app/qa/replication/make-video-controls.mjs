async function main() {
  const flags = process.argv.slice(2).filter((a) => a.startsWith('-'));
  if (flags.includes('--truth')) {
    printTruth();
    return;
  }
  const wanted = process.argv.slice(2).filter((a) => !a.startsWith('-'));
  // `motion` اختصارٌ لشواهد الحركة الثمانية — لأن إعادةَ توليدها وحدها هو ما
  // يتكرّر أثناء معايرة بنودها، وكتابةُ ثمانية أسماءٍ في كلّ مرّة تُغري بالنسيان.
  const names = wanted.length
    ? wanted.flatMap((n) => (n === 'motion' ? Object.keys(MODES).filter((k) => k.startsWith('motion-')) : [n]))
    : Object.keys(MODES);
  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const name of names) {
    const mode = MODES[name];
    if (!mode) {
      console.error(`لا شاهد باسم «${name}» — المتاح: ${Object.keys(MODES).join(' · ')}`);
      process.exit(2);
    }
    const out = await encode(mode);
    const kb = (fs.statSync(out).size / 1024).toFixed(0);
    console.log(`${name.padEnd(7)} ${mode.width}×${mode.height}  ${kb}KB  ${mode.label}`);
    console.log(`        ${out}`);
  }
}

